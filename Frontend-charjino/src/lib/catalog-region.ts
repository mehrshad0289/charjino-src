export function catalogRegionLabel(value?: string | null) {
  const raw = typeof value === 'string' ? value.trim() : '';
  if (!raw) return '';
  if (/[\u0600-\u06FF]/.test(raw)) return raw;
  return LABELS[raw.toLowerCase()] ?? raw.toUpperCase();
}
