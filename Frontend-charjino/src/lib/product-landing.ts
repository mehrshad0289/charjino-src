function familyOf(product: CatalogProduct) {
  return (product.fulfillmentType ?? '').trim();
}

function regionLine(product: CatalogProduct) {
  const label = catalogRegionLabel(product.region);
  if (label) {
    return `ریجن این کالا «${label}» است. قبل از پرداخت با ریجن فروشگاه یا لانچر خودتان مطابقت بدهید؛ سفارش با ریجن اشتباه معمولاً قابل اصلاح نیست.`;
  }
  return 'اگر این کالا ریجن مشخص دارد، همان را روی صفحه ببینید و با حساب خودتان یکی کنید. کالای بدون محدودیت منطقه را هم فقط از همین صفحه بخرید.';
}

function nameOf(product: CatalogProduct) {
  return productHeading(product);
}

