export function getCategoryLanding(slug?: string | null): CategoryLanding | null {
  const id = slug?.trim() as MainCategorySlug | undefined;
  if (!id || !(id in CATEGORY_LANDINGS)) {
    return null;
  }
  return CATEGORY_LANDINGS[id];
}

export function hasCategoryLanding(slug?: string | null) {
  return Boolean(getCategoryLanding(slug));
}

export function shouldShowCategoryLanding(input: {
  slug?: string | null;
  q?: string;
  page?: number;
  platform?: string;
  region?: string;
  sort?: string;
  hasHub?: boolean;
}) {
  if (!getCategoryLanding(input.slug) && !input.hasHub) {
    return false;
  }
  if ((input.q ?? '').trim()) {
    return false;
  }
  if ((input.page ?? 1) > 1) {
    return false;
  }
  if ((input.platform ?? '').trim() || (input.region ?? '').trim()) {
    return false;
  }
  const sort = (input.sort ?? 'listed').trim();
  return !sort || sort === 'listed';
}
